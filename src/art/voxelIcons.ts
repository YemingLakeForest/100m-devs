/**
 * A hero's head, for the link tiles that stand for their tree. The demo's
 * blocks, in each person's own colours: James's orange hair and Diet Coke,
 * Serena's long black hair, Billy's tie, Matt's headset, your glasses.
 */
export function headBoxes(hero: 'you' | 'james' | 'billy' | 'serena' | 'matt'): readonly Box[] {
  const look: Record<typeof hero, { shirt: MaterialId; skin: MaterialId; hair: MaterialId }> = {
    you: { shirt: 'bl', skin: 'sk', hair: 'hbr' },
    james: { shirt: 'wh', skin: 'sk', hair: 'or' },
    billy: { shirt: 'pu', skin: 'sk', hair: 'hbl' },
    serena: { shirt: 'rd', skin: 'sk2', hair: 'hbk' },
    matt: { shirt: 'gr', skin: 'sk2', hair: 'hbr' },
  }
  const { shirt, skin, hair } = look[hero]
  const b: Box[] = [[1.5, 1.5, 0, 2, 2, 1.4, shirt], [1.5, 1.5, 1.4, 2, 2, 1.9, skin], [1.4, 1.4, 3.3, 2.2, 2.2, 0.7, hair]]
  if (hero === 'james') b.push([3.9, 2.3, 0, 0.7, 0.7, 1.3, 'si'], [3.9, 2.3, 0.4, 0.7, 0.7, 0.4, 'cr'])
  if (hero === 'serena') b.push([1.4, 1.4, 1.5, 0.35, 2.2, 1.9, hair])
  if (hero === 'billy') b.push([2.3, 3.52, 0.4, 0.4, 0.05, 1, 'dk'])
  if (hero === 'matt') b.push([3.52, 2, 1.9, 0.2, 0.9, 0.9, 'bk'], [1.4, 1.4, 3.9, 2.2, 0.3, 0.3, 'bk'])
  if (hero === 'you') b.push([1.6, 3.52, 1.9, 0.8, 0.05, 0.3, 'bk'], [2.6, 3.52, 1.9, 0.8, 0.05, 0.3, 'bk'])
  return b
}
