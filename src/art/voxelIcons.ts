/**
 * The upgrade trees' voxel icons — GDD §8, ART_DIRECTION §3.1 [ported 2026-09-26].
 *
 * The rebuild's demo drew every node as a little isometric object — a garage,
 * a beanbag, a stack of Diet Coke — made of boxes. They are the part of the
 * demo that says *what* a node is before its name is read, so they come over
 * whole: same boxes, same proportions, same five-unit footprint.
 *
 * **What changed is where the colour comes from.** The demo shaded each face by
 * mixing its colour toward white or black, which invents a new colour per face
 * per state — exactly what ART_DIRECTION §5's quantiser exists to stop. Here
 * every box is a *material*: three entries from the master palette, lit top,
 * front and shaded side, which are neighbouring steps of one ramp wherever the
 * ramp has them. So an icon is drawn from §2.2's 37 colours and nothing else,
 * and a new icon cannot drift off it.
 *
 * These are world objects on an interface board — a garage is a garage — so
 * they use the world ramps, as a cover on the gallery wall does. Two dated
 * borrowings (ART_DIRECTION §2.1a): the world has no red and no yellow, and a
 * big red button, a fire, a rocket fin and a Diet Coke can are red for a reason,
 * so those take ALARM and WARN; and the one purple thing (Billy) takes the
 * RARITY violet. A locked icon is not drawn in these at all: `hud/isoBoard.ts`
 * draws it as a phosphor ghost, so nothing here needs a dimmed variant.
 *
 * Boxes are `[x, y, z, w, d, h, material]` in icon units, the footprint 0..5.
 */

